function t(key, params = {}) {
    let currentLang = localStorage.getItem('jitterfx-lang') || 'en';
    if (!i18n[currentLang]) currentLang = 'en';
    let text = i18n[currentLang][key] || i18n['en'][key] || key;
    for (const [k, v] of Object.entries(params)) {
        text = text.replace(`{${k}}`, v);
    }
    return text;
}

function applyTranslations() {
    document.title = t("title");
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (el.tagName === 'INPUT' && el.type === 'text') {
            el.placeholder = t(key);
        } else if (el.tagName === 'OPTION') {
            el.innerText = t(key);
        } else {
            const span = el.querySelector('span');
            if (span && span.querySelector('svg')) {
                const svgClone = span.querySelector('svg').cloneNode(true);
                if (el.hasAttribute('data-i18n-tip')) {
                    span.title = t(el.getAttribute('data-i18n-tip'));
                }
                el.innerText = t(key) + ' ';
                span.innerHTML = '';
                span.appendChild(svgClone);
                el.appendChild(span);
            } else {
                el.innerText = t(key);
            }
        }
    });
    
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        el.innerHTML = t(key);
    });
    
    document.querySelectorAll('[data-i18n-tip-only]').forEach(el => {
        const key = el.getAttribute('data-i18n-tip-only');
        el.title = t(key);
    });
}

window.addEventListener('DOMContentLoaded', () => {
    const langSelect = document.getElementById('langSelect');
    if (langSelect) {
        langSelect.value = localStorage.getItem('jitterfx-lang') || 'en';
        langSelect.addEventListener('change', (e) => {
            localStorage.setItem('jitterfx-lang', e.target.value);
            applyTranslations();
            if(typeof updateEstimate === 'function') updateEstimate();
        });
    }
    applyTranslations();
});
